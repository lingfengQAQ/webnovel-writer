/** Import an explicitly reviewed Archify artifact; never executed by production or build. */
import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const [htmlPath, candidatePath] = process.argv.slice(2)
if (!htmlPath || !candidatePath) throw new Error('Supply the reviewed HTML and candidate JSON')
const html = fs.readFileSync(htmlPath, 'utf8')
const candidate = JSON.parse(fs.readFileSync(candidatePath, 'utf8'))
const match = html.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/)
if (!match || !match[1].includes('data-quality-profile="showcase"')) throw new Error('Missing reviewed diagram')
const viewBox = match[1].match(/viewBox="([^"]+)"/)?.[1].split(/\s+/).map(Number)
if (!viewBox || viewBox.length !== 4 || !viewBox.every(Number.isFinite)) throw new Error('Invalid viewBox')
let svg = match[2].replace(/<!--[\s\S]*?-->/g, '').replace(/<title\b[^>]*>[\s\S]*?<\/title>/g, '').replace(/<desc\b[^>]*>[\s\S]*?<\/desc>/g, '')
svg = svg.replace(/\sdata-node-context="[^"]*"/g, '').replace(/\saria-label="[^"]*"/g, '')
if (/<(?:script|foreignObject|iframe|image|use|style)\b|\son\w+\s*=|\b(?:href|src)\s*=|url\((?!#)/i.test(svg)) throw new Error('Only inert inline diagram shapes are accepted')
const ids = [...svg.matchAll(/data-node-id="([^"]+)"/g)].map(m => m[1])
if (ids.join() !== candidate.components.map(n => n.id).join()) throw new Error('Diagram/candidate nodes differ')
const nodes = candidate.components.map(({id,label,pos,size,sublabel}) => ({id,label,x:pos[0],y:pos[1],width:size[0],height:size[1],...(sublabel ? {sublabel} : {})}))
const edges = candidate.connections.map(({id,from,to,label}) => ({id,from,to,...(label ? {label} : {})}))
const license = fs.readFileSync(new URL('../licenses/archify.txt', import.meta.url), 'utf8')
const source = [
'/*! Archify 3.0.1 generated artwork and semantic styling.',
license.trim(), '*/',
'// Generated by scripts/import-workflow-artwork.mjs. Geometry is the selected diagram.',
'export const artworkSourceHash = '+JSON.stringify(createHash('sha256').update(fs.readFileSync(htmlPath)).digest('hex')),
'export const artworkViewBox = '+JSON.stringify(viewBox)+' as const',
'export const artworkNodes = '+JSON.stringify(nodes,null,2)+' as const',
'export const artworkEdges = '+JSON.stringify(edges,null,2)+' as const',
'export const artworkSvg = '+JSON.stringify(svg.trim()), ''
].join('\n')
fs.writeFileSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/client/workflow-artwork.ts'), source)
console.log('Imported '+nodes.length+' nodes and '+edges.length+' edges')
